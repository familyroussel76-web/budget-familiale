-- Budget Familial V3.2.0 — historique des transferts
create table if not exists public.transferts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mois text not null,
  enveloppe_source text not null,
  enveloppe_destination text not null,
  montant numeric(12,2) not null check (montant > 0),
  ajoute_par text,
  created_at timestamptz not null default now()
);

alter table public.transferts enable row level security;

drop policy if exists "transferts_select_own" on public.transferts;
create policy "transferts_select_own" on public.transferts for select using (auth.uid() = user_id);
drop policy if exists "transferts_insert_own" on public.transferts;
create policy "transferts_insert_own" on public.transferts for insert with check (auth.uid() = user_id);
drop policy if exists "transferts_delete_own" on public.transferts;
create policy "transferts_delete_own" on public.transferts for delete using (auth.uid() = user_id);

do $$ begin
  alter publication supabase_realtime add table public.transferts;
exception when duplicate_object then null;
end $$;
